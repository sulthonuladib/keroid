#!/usr/bin/env python3
"""Generate the Kotlin Ghostty theme catalogue from Ghostty's shipped themes.

The colours are the ones Ghostty itself ships, as generated by MyGo from
ghostty-themes-release-20260921-150923-0b55a9e.tgz (iTerm2-Color-Schemes,
MIT; each individual theme keeps its author's copyright):

    ghostty_themes.go in github.com/egoist/mygo,
    plugins/terminal, generated by `go generate` (internal/libbuild).

MyGo is not a build dependency. We read the generated table once, verify its
hash, and emit Kotlin data that this project owns. Re-run this script only to
refresh the catalogue:

    MYGO_TERMINAL_DIR=<.../plugins/terminal> ./scripts/gen-terminal-themes.py
"""

from __future__ import annotations

import hashlib
import os
import re
import sys

PINNED_SHA256 = "5a87ca81f4f0aec1ed9617149e89e0b735095f71386aa118bbfd2ab797cf6dca"
DEFAULT_DIR = (
    os.path.expanduser("~/go/pkg/mod/github.com/egoist/mygo"
                       "@v0.6.5-0.20261025164211-a5145e193a49/plugins/terminal")
)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "app/src/main/kotlin/com/sulthonuladib/keroid/term/TerminalThemes.kt")

ENTRY = re.compile(r'\{"((?:[^"\\]|\\.)*)", \[22\]uint32\{([^}]*)\}\}')


def signed_int(argb: int) -> int:
    """An ARGB value as the signed 32-bit Int Kotlin stores."""
    return argb - (1 << 32) if argb > 0x7FFFFFFF else argb


def main() -> int:
    src = os.environ.get("MYGO_TERMINAL_DIR", DEFAULT_DIR)
    path = os.path.join(src, "ghostty_themes.go")
    try:
        raw = open(path, "rb").read()
    except OSError as e:
        print(f"cannot read {path}: {e}", file=sys.stderr)
        return 2
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED_SHA256:
        print(f"{path} changed (sha256 {digest}); review the new themes, then "
              f"update PINNED_SHA256 deliberately", file=sys.stderr)
        return 1

    text = raw.decode("utf-8")
    entries = []
    for match in ENTRY.finditer(text):
        name = match.group(1).encode().decode("unicode_escape") if "\\" in match.group(1) else match.group(1)
        values = [v.strip() for v in match.group(2).split(",") if v.strip()]
        if len(values) != 22:
            print(f"{name}: expected 22 colours, got {len(values)}", file=sys.stderr)
            return 1
        entries.append((name, values))
    if len(entries) < 500:
        print(f"only {len(entries)} themes parsed; refusing to overwrite", file=sys.stderr)
        return 1
    # GhosttyThemes() sorts as Ghostty lists them: case-insensitively, then by name.
    entries.sort(key=lambda e: (e[0].lower(), e[0]))

    lines = [
        "package com.sulthonuladib.keroid.term",
        "",
        "// Generated by scripts/gen-terminal-themes.py from the themes Ghostty ships.",
        "// Source: ghostty-themes-release-20260921-150923-0b55a9e.tgz, as generated into",
        "// mygo/plugins/terminal/ghostty_themes.go (sha256",
        f"// {PINNED_SHA256}).",
        "// iTerm2-Color-Schemes collection: MIT, Copyright (c) 2011 to Present",
        "// Mark Badolato; each individual theme keeps its author's copyright.",
        "// Do not edit by hand.",
        "",
        "/**",
        " * One Ghostty theme: the 16 program colours and the six chrome colours, in",
        " * Ghostty's own order. Colors are opaque ARGB ints.",
        " */",
        "data class TerminalTheme(val name: String, val colors: IntArray) {",
        "    init {",
        "        require(colors.size == COLOR_COUNT) { \"$name: ${colors.size} colours\" }",
        "    }",
        "",
        "    val background: Int get() = colors[16]",
        "    val foreground: Int get() = colors[17]",
        "    val cursor: Int get() = colors[18]",
        "    val cursorText: Int get() = colors[19]",
        "    val selection: Int get() = colors[20]",
        "    val selectionText: Int get() = colors[21]",
        "",
        "    /** The 16 program colours: black, red, green, yellow, blue, magenta, cyan, white, then bright. */",
        "    val palette: IntArray get() = colors.copyOfRange(0, 16)",
        "",
        "    /** Whether this theme is meant for a dark terminal, judged by its background. */",
        "    val isDark: Boolean get() = luminance(background) < 0.5f",
        "",
        "    companion object {",
        "        const val COLOR_COUNT = 22",
        "    }",
        "}",
        "",
        "/** Relative luminance of an opaque ARGB int, 0 (black) to 1 (white). */",
        "internal fun luminance(argb: Int): Float {",
        "    fun channel(shift: Int): Float {",
        "        val value = ((argb shr shift) and 0xFF) / 255f",
        "        return if (value <= 0.04045f) value / 12.92f",
        "        else ((value + 0.055f) / 1.055f).let { it * it * it }",
        "    }",
        "    return 0.2126f * channel(16) + 0.7152f * channel(8) + 0.0722f * channel(0)",
        "}",
        "",
        "/** Every theme Ghostty ships, sorted by name as `ghostty +list-themes` shows them. */",
        "object TerminalThemes {",
        "    // Built in batches: one literal list of 600+ themes overflows a JVM method.",
        "    val all: List<TerminalTheme> = buildList {",
    ]
    batch = 100
    for start in range(0, len(entries), batch):
        lines.append(f"        addAll(batch{start // batch}())")
    lines += [
        "    }",
        "",
    ]
    for start in range(0, len(entries), batch):
        lines.append(f"    private fun batch{start // batch}(): List<TerminalTheme> = listOf(")
        for name, values in entries[start:start + batch]:
            # Opaque ARGB, signed decimal so each entry stays a plain Int literal
            # (`0xFF...` would be a Long). Several themes legitimately use 0x000000.
            colors = ", ".join(str(signed_int(0xFF000000 | int(v, 16))) for v in values)
            escaped = name.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'        TerminalTheme("{escaped}", intArrayOf({colors})),')
        lines += ["    )", ""]
    lines += [
        "    /** Case-insensitive lookup, as Ghostty's theme option matches names. */",
        "    fun byName(name: String): TerminalTheme? =",
        "        all.firstOrNull { it.name == name } ?: all.firstOrNull { it.name.equals(name, ignoreCase = true) }",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as out:
        out.write("\n".join(lines))
    print(f"wrote {len(entries)} themes to {os.path.relpath(OUT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
